    ap.add_argument("--fresh_forward", action="store_true",
                    help="additionally run the self-contained counterfactual forward pass (ChronosLLM.from_pretrained + "
                         "teacher-forced, checkpoint switchable via --model_path) -- needs a GPU")
    ap.add_argument("--model_path", default=DEFAULT_MODEL_PATH,
                    help="checkpoint for fresh_forward; the only thing to change when evaluating a new checkpoint")
    ap.add_argument("--fresh_parquet", default=DEFAULT_FRESH_PARQUET)
    ap.add_argument("--fresh_n_samples", type=int, default=80)
    ap.add_argument("--fresh_seed", type=int, default=0)
    ap.add_argument("--fresh_batch_size", type=int, default=16)
    ap.add_argument("--gate_scales", default="1.0",
                    help="comma-separated list of gate multipliers; main result = 1.0, pass e.g. 10,50 as a mechanism check "
                         "(gates are switched within one model load, the 9B is not reloaded)")
    ap.add_argument("--dump_examples", type=int, default=3,
                    help="store the rendered-text tail of the first N sampled rows for every band in the output JSON, for manual verification that the edit took effect")
    ap.add_argument("--fresh_output", default="outputs/eval/causal_faithfulness/fresh_forward_result.json")
    ap.add_argument("--fresh_variant_mode", choices=["conclusion", "advisory"], default="conclusion",
                    help="counterfactual edit interface: conclusion = replace only the final magnitude sentence of the "
                         "conclusion (historical default, same convention as the 444-row pipeline); advisory = inject "
                         "through the cfaug training interface (advisory section in the prompt + reasoning/conclusion "
                         "templates citing it, triply redundant magnitude signal, zero residue of the old magnitude), "
                         "used to decide whether the loss of directional semantics is a representation limit or an "
                         "evaluation-interface mismatch")
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--save_per_sample_raw", default=None,
                    help="additionally dump the raw per-sample, per-band peak_ratio/mean_ratio matrices (npz) for "
                         "post-hoc band-label shuffling / null-distribution analysis; off by default, does not affect "
                         "existing behaviour or published numbers. Single --gate_scales only (several raise an error)")
