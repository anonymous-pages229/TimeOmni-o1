"""Causal-faithfulness check: does the numeric forecast produced by Chronos-2 actually follow the
textual instruction generated by the LLM? (This is *not* about whether the text itself is accurate;
that is covered by the understanding / text-quality evaluations.)

Two-step method:
  (a) gate=0 identity ablation -- already covered by ``chronos_llm/tests/test_cross_attn_identity.py``
      (with gate=0 the output is numerically identical to the original Chronos-2). This script's
      ``gate_identity_report()`` re-runs that check in place with the same loader so the report is
      self-contained (no dependency on having run that test file first).
  (b) counterfactual test -- same context, different conclusions, teacher-forced; check whether the
      forecast moves in the direction the instruction states.

(b) does not reinvent the wheel: a more systematic implementation already exists as a three-part
  pipeline -- ``chronos_llm/scripts/utils/make_controllability_parquets.py`` (edits the conclusion into
  5 magnitude bands) + ``controllability_infer.sh`` (batched teacher-forced inference with feedback,
  ``MODEL_PATH`` accepts any checkpoint) + ``eval_controllability_metrics.py`` (Spearman monotonicity /
  direction-agreement rate). That is exactly a systematised counterfactual test (a 5-band sweep goes
  beyond a single one-off check). Its outputs are expected under
  ``outputs/eval/controllability{,_gs10,_gs50}/`` for gate_scale in {1, 10, 50}.

This script does not re-run that inference pipeline; it adds three things:
  1. Aggregates / rephrases the existing outputs into a "causal faithfulness report" in the paper's
     wording (we claim explainability, not controllability; the underlying mechanism and numbers are
     the same -- "does the forecast follow the instruction direction" is the definition of causal
     faithfulness).
  2. (Supplementary cross-check, ``--vlm_judge``) renders the forecast curves as images and asks the
     local Qwen3.5-9B (its native multimodal ``Qwen3_5ForConditionalGeneration`` class, completely
     independent of the ChronosLLM used for training/inference -- it merely shares the weights and acts
     as a generic VLM judge) which of two counterfactual forecast curves looks more like "the direction
     the instruction states".
  3. (``--fresh_forward``) a self-contained counterfactual forward pass that does not depend on the
     controllability_infer.sh shell pipeline: this file itself calls ``ChronosLLM.from_pretrained`` +
     ``generate_forecast_teacher_forced`` (``fresh_forward_report()``) on 50-100 sampled rows -- single
     file, single command, checkpoint path as a CLI argument (``--model_path``) -- with a plumbing
     self-check (did the edit really change the rendered text / the prediction tensor? used to separate
     "genuinely unfaithful" from "the script itself is buggy") and a ``--gate_scales`` mechanism check
     (switch the gate multiplier within one model load, no reload of the 9B). Together with the full
     444-row aggregation in (b) these are two independent implementations that cross-validate each other.

To re-run on a new checkpoint, pick one of:
  (i) the existing three-part pipeline (all 444 rows, more statistical power):
      MODEL_PATH=<new checkpoint dir> OUT_ROOT=outputs/eval/controllability_<tag> \\
        bash chronos_llm/scripts/utils/controllability_infer.sh
      python chronos_llm/eval/causal_faithfulness.py --roots outputs/eval/controllability_<tag>:<tag>
  (ii) the self-contained forward pass in this file (50-100 sampled rows, single command, no shell
       pipeline needed):
      python chronos_llm/eval/causal_faithfulness.py --fresh_forward --skip_aggregate \\
        --model_path <new checkpoint dir> --gate_scales 1.0,10,50 --fresh_n_samples 80

Usage:
  python chronos_llm/eval/causal_faithfulness.py                        # aggregate the three existing runs
  python chronos_llm/eval/causal_faithfulness.py --vlm_judge --n_samples 20   # add the VLM judge
  python chronos_llm/eval/causal_faithfulness.py --fresh_forward --skip_aggregate \\
    --gate_scales 1.0,10,50 --fresh_n_samples 80    # self-contained counterfactual forward (see (ii))
"""
