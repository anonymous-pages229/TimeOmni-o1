    if args.fresh_forward:
        print("\n" + "=" * 70)
        print("Self-contained counterfactual forward pass (this file calls ChronosLLM.from_pretrained + teacher-forced "
              "directly; checkpoint switchable, see section (b') in the module docstring)")
        print("=" * 70)
        gate_scales = [float(x) for x in args.gate_scales.split(",") if x.strip()]
        fresh_forward_report(
            args.model_path, args.fresh_parquet, n_samples=args.fresh_n_samples,
            seed=args.fresh_seed, batch_size=args.fresh_batch_size, device=args.device,
            gate_scales=gate_scales, dump_examples=args.dump_examples, output=args.fresh_output,
            variant_mode=args.fresh_variant_mode, save_per_sample_raw=args.save_per_sample_raw,
        )

    if args.vlm_judge:
        print("\n" + "=" * 70)
        print("Supplementary cross-check: Qwen3.5-9B as an independent VLM judge")
        print("=" * 70)
        vlm_judge_report(n_samples=args.n_samples)

    if results:
        print("\n" + "=" * 70)
        print("Summary (all 444 rows; the three gate_scale runs produced by controllability_infer.sh)")
        print("=" * 70)
        for r in results:
            print(f"  {r['label']}: pair_dir_rate={r['pair_dir_rate']:.3f} "
                  f"spearman={r['spearman_mean']:.3f} -> {r['verdict']}")


