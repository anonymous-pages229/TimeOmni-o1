# Wording of the 5 magnitude-band instructions: verbatim copy of the BANDS dict in
# scripts/utils/make_controllability_parquets.py (the edit text actually behind the npz files aggregated by
# counterfactual_report), cross-checked against the _MAG_BANDS keyword families in rl/reward.py
# (well_below/mod_below hit "well below"/"moderately below", above hits "well above", tiny hits
# "small fraction" -- above/well_below are the most extreme "opposite direction" counterfactual pair).
BAND_CLAUSES = {
    "tiny": "the peak reaches only a small fraction of the series' typical high level",
    "well_below": "the peak runs well below the series' typical highs",
    "mod_below": "the peak sits moderately below the series' typical highs",
    "typical": "the peak sits close to the series' typical high level",
    "above": "the peak runs well above the series' typical highs",
}
_OVERALL_RE = re.compile(r"\s*Overall,.*$", re.S)
_MAGTAG_RE = re.compile(r"^\[Magnitude:\s*[A-Z_]+\]\s*")
_OPPOSITE_PAIRS = [("above", "well_below"), ("above", "tiny")]


def edit_conclusion(concl, clause, band=None):
    """Strip any existing "Overall, ..." magnitude sentence and append the one for the requested band;
    verbatim-identical to make_controllability_parquets.edit_conclusion (the intervention is decoupled
    from the event text: only the conclusion changes, reasoning/background/event are left untouched
    together with history_values).
    When ``band`` is not None the leading `[Magnitude: TAG]` structured tag (make_structured_conclusion
    format) is replaced as well -- otherwise the prefix tag still carries the original band and
    contradicts the edited final sentence, making the counterfactual impure (on a checkpoint trained on
    tagged conclusions, editing only the final sentence dropped Spearman from normal levels to 0.06;
    that was the evaluation lagging behind the new data format, not the model being unfaithful)."""
    s = str(concl)
    prefix = ""
    m = _MAGTAG_RE.match(s)
    if m:
        s = s[m.end():]
        prefix = f"[Magnitude: {BAND_TAG[band]}] " if band is not None else m.group(0)
    base = _OVERALL_RE.sub("", s).rstrip()
    if base and base[-1] not in ".!?":
        base += "."
    return f"{prefix}{base} Overall, {clause}."


def _roi_span(row):
    """Span logic of the cfaug training rows (same as make_cfaug_parquet.make_cf_row): prefer
    roi_start/end_idx; if missing/invalid fall back to [past_len, past_len+future_len) (absolute
    coordinates, matching the corpus convention)."""
    def _safe_int(v):
        try:
            f = float(v)
        except (TypeError, ValueError):
            return None
        return int(f) if np.isfinite(f) else None

    rs, re_ = _safe_int(row.get("roi_start_idx")), _safe_int(row.get("roi_end_idx"))
    if rs is None or re_ is None or re_ <= rs:
        pl, fl = _safe_int(row.get("past_len")), _safe_int(row.get("future_len"))
        if pl is None or fl is None:
            raise RuntimeError(
                f"row id={row.get('id')} has no ROI and lacks past_len/future_len; cannot build the advisory variant span")
        rs, re_ = pl, pl + fl
    return rs, re_


def apply_advisory_variant(sub, band):
    """Build counterfactual variants through the **cfaug training interface** (reuses the text rewrite of
    make_cfaug_parquet.make_cf_row; future/history are untouched -- we test "does the forecast follow the
    instruction", we are not building training data):
      - insert an External magnitude advisory section before `## Task` in the user prompt;
      - replace reasoning/conclusion with templates that cite the advisory (zero residue of the old magnitude).
    Compared with the default interface (edit only the final conclusion sentence), this separates whether
    the observed "well_below ~ above" loss of directional semantics is a genuine resolution limit of the
    feedback representation or a mismatch between the evaluation and training interfaces (during training
    the magnitude signal is triply redundant -- advisory + reasoning + conclusion -- whereas the evaluation
    gives only a single hint in the final conclusion sentence)."""
    from chronos_llm.scripts.utils.make_cfaug_parquet import (
        ADVISORY_SECTION,
        CONCLUSION_TMPL,
        REASONING_TMPL,
    )
    clause = BAND_CLAUSES[band]  # verbatim-identical to make_cfaug_parquet.BAND_CLAUSES (asserted by test_cfaug_parquet)
    sec = ADVISORY_SECTION.format(clause=clause)
    prompts, reasonings, concls = [], [], []
    for _, row in sub.iterrows():
        rs, re_ = _roi_span(row)
        prompt = str(row.get("prompt") or "")
        marker = "\n## Task"
        if marker in prompt:  # insert before ## Task (as in the cfaug training rows); append at the end if absent
            i = prompt.index(marker)
            prompts.append(prompt[:i] + "\n" + sec + prompt[i:])
        else:
            prompts.append(prompt.rstrip() + "\n\n" + sec)
        reasonings.append(REASONING_TMPL.format(rs=rs, re=re_, clause=clause))
        concls.append(CONCLUSION_TMPL.format(rs=rs, re=re_, clause=clause))
    sub = sub.copy()
    sub["prompt"], sub["reasoning"], sub["conclusion"] = prompts, reasonings, concls
    return sub


def _variant_dataset(base_ds, sub_df):
    """Shallow-copy base_ds (reusing its tokenizer / rendering hyper-parameters) and swap only the df --
    all variants share one rendering code path (build_supervised_ids' LCP supervision locator etc.)
    instead of re-deriving the input format."""
    v = copy.copy(base_ds)
    v.df = sub_df.reset_index(drop=True)
    v._skip = set()
    return v


def _build_items_strict(ds):
    """Call _build_item row by row and require non-None, bypassing __getitem__'s lazy skip-and-substitute.
    A diagnostic script needs strict row alignment: any row whose edited rendering fails (too long / no
    supervised content) must fail loudly instead of being silently replaced by another sample (otherwise
    the row order across variants drifts silently and every row-wise comparison is wrong)."""
    items = []
    for i in range(len(ds)):
        it = ds._build_item(i)
        if it is None:
            row = ds.df.iloc[i]
            raise RuntimeError(
                f"row {i} (id={row.get('id')}) failed to render after the counterfactual edit (too long / no supervised content) -- "
                "the diagnostic requires strict row alignment; inspect this row or lower --fresh_n_samples to resample")
        items.append(it)
    return items


def _gate_params(model):
    return [(n, p) for n, p in model.named_parameters() if "chronos" in n and "cross_attn.gate" in n]


def _row_peak_mean(qp_row, valid_row, roi_row, median_idx):
    """Peak / mean of the q0.5 median forecast curve within ROI∩valid (falls back to all valid positions
    when the ROI is empty) -- same convention as counterfactual_report/_pred_peaks (median quantile, ROI
    first, valid as fallback)."""
    med = qp_row[median_idx]
    roi = roi_row.astype(bool) & valid_row.astype(bool)
    m = roi if roi.any() else valid_row.astype(bool)
    if not m.any():
        return float("nan"), float("nan")
    vals = med[m]
    return float(np.nanmax(vals)), float(np.nanmean(vals))


def _rank_summary(mat, orig, ok_mask, band_order):
    """mat/orig: (len(band_order), N) / (N,) peak or mean ratios normalised by typ. Spearman is invariant to a
    positive per-row rescaling (typ is one constant across the 5 bands of a row) -- the normalisation only
    makes the "response magnitude" comparable across datasets; it does not affect the correlation or the
    direction-agreement rate."""
    idx = np.where(ok_mask)[0]
    rhos, strict = [], 0
    for i in idx:
        col = mat[:, i]
        if np.isfinite(col).all():
            r = spearmanr(np.arange(len(band_order)), col).statistic
            if np.isfinite(r):
                rhos.append(r)
                strict += int(np.all(np.diff(col) > 0))
    rhos = np.array(rhos)
    out = {
        "n": int(len(idx)), "n_finite_spearman": int(len(rhos)),
        "spearman_mean": float(np.mean(rhos)) if rhos.size else float("nan"),
        "spearman_pos_rate": float(np.mean(rhos > 0)) if rhos.size else float("nan"),
        "strict_mono_rate": float(strict / len(rhos)) if rhos.size else float("nan"),
    }
    for a, b in _OPPOSITE_PAIRS:
        ai, bi = band_order.index(a), band_order.index(b)
        va, vb = mat[ai, idx], mat[bi, idx]
        ok = np.isfinite(va) & np.isfinite(vb)
        out[f"dir_follow_rate({a}>{b})"] = float(np.mean(va[ok] > vb[ok])) if ok.any() else float("nan")
    dev = float(np.nanmean([np.nanmean(np.abs(mat[b, idx] - orig[idx])) for b in range(len(band_order))]))
    out["mean_abs_dev_vs_orig"] = dev
    out["ratio_orig"] = float(np.nanmean(orig[idx])) if idx.size else float("nan")
    for b, name in enumerate(band_order):
        out[f"ratio_{name}"] = float(np.nanmean(mat[b, idx])) if idx.size else float("nan")
    return out


def fresh_forward_report(model_path, parquet, n_samples=80, seed=0, batch_size=16,
                         max_user_tokens=1500, max_tokens=4096, device="cuda",
                         gate_scales=(1.0,), dump_examples=3, output=None,
                         variant_mode="conclusion", save_per_sample_raw=None):
    """Self-contained counterfactual test: load with ChronosLLM.from_pretrained -> edit the conclusion of
    the same sampled rows band by band (history_values/background/event/reasoning all unchanged) ->
    generate_forecast_teacher_forced forward pass (no autoregressive generate; teacher-force directly and
    feed the hidden states back into Chronos-2 -- the same code path as the teacher-forced reference mode
    of chronos_llm/eval/infer_forecast.py) -> compare the peak / mean of the median (q0.5) forecast curve
    within ROI∩valid.

    Relation to counterfactual_report(): the latter aggregates the already-computed 444-row results (more
    statistical power); this is a self-contained single-file reproduction of the same methodology (50-100
    sampled rows, checkpoint path switchable from the CLI, plumbing self-check) for independent
    cross-validation and "re-run a new checkpoint with one command".

    ``save_per_sample_raw``: default None (existing behaviour and published numbers unaffected). When a
    path is given, additionally dump the raw per-sample, per-band ``peak_ratio``/``mean_ratio`` matrices
    (intermediate data that ``_rank_summary`` discards after computing the aggregates). ``_rank_summary``
    keeps only the aggregated Spearman / direction-agreement numbers; without this raw data one cannot do
    post-hoc analyses such as "shuffle the band labels and recompute the null distribution". **Single
    gate_scale only** (raises when ``len(gate_scales) > 1`` -- multi-scale runs are the mechanism check,
    not the null-hypothesis use case this parameter serves; avoids over-engineering).
    """
    if save_per_sample_raw and len(gate_scales) > 1:
        raise ValueError(
            "--save_per_sample_raw supports a single gate_scale only (several were given, so it is unclear "
            "which one's raw matrices to save) -- multi-scale runs are the mechanism check, unrelated to the null-hypothesis use case of this flag")
    import torch
    from chronos_llm.data.collator import ChronosLLMCollator
    from chronos_llm.data.forecast_dataset import ForecastParquetDataset
    from chronos_llm.eval.metrics import _median_index
    from chronos_llm.eval.text_alignment_eval import domain_of
    from chronos_llm.models.chronos_llm_model import ChronosLLM

    print(f"[fresh_forward] loading model {model_path} ...")
    model = ChronosLLM.from_pretrained(model_path, merge=True).eval().to(device)
    tok = model.tokenizer
    median_idx = _median_index(model.chronos.quantiles.detach().cpu().float().numpy())
    collator = ChronosLLMCollator(tokenizer=tok)

    base_ds = ForecastParquetDataset(
        parquet, tok, split="test", inference_mode=False, emit_meta=False,
        max_user_tokens=max_user_tokens, max_tokens=max_tokens,
    )
    full_df = base_ds.df
    print(f"[fresh_forward] usable test rows = {len(full_df)}")
    # Per-dataset "typical peak" = p90 of the future peaks over *all* (unsampled) test rows of that dataset --
    # same convention as (b); estimating on the full test set rather than the sampled subset is more
    # stable. _peak() is the same function used in (b).
    typ_map = full_df["future_values"].map(_peak).groupby(full_df["dataset_name"]).quantile(0.90).to_dict()

    rng = np.random.default_rng(seed)
    n = min(n_samples, len(full_df))
    idx = np.sort(rng.choice(len(full_df), size=n, replace=False))
    sub_df_base = full_df.iloc[idx].reset_index(drop=True)
    ds_names = sub_df_base["dataset_name"].astype(str).to_numpy()
    ids = (sub_df_base["id"].astype(str).to_numpy() if "id" in sub_df_base.columns
           else np.array([str(i) for i in range(n)]))
    typ = np.array([typ_map.get(d, np.nan) for d in ds_names])
    typ_ok = np.isfinite(typ) & (typ > 1e-9)
    print(f"[fresh_forward] sampled {n} rows (seed={seed}), "
          f"dataset_name coverage: {sub_df_base['dataset_name'].value_counts().to_dict()}")
    # Reuse the same 10->5 domain mapping as text_alignment_eval (the paper's main-table convention)
    # instead of redefining it here and risking drift; sources outside the list go to "Unknown" (never
    # silently dropped).
    domains = np.array([domain_of(d) or "Unknown" for d in ds_names])

    gate_snapshot = [p.detach().clone() for _, p in _gate_params(model)]
    if not gate_snapshot:
        raise RuntimeError("no chronos cross_attn.gate parameters found in the model -- does this checkpoint architecture lack gated cross-attention?")
    print(f"[fresh_forward] found {len(gate_snapshot)} chronos cross_attn.gate scalar parameters")

    def _to_device(batch):
        return {k: (v.to(device) if torch.is_tensor(v) else v) for k, v in batch.items()}

    def _run_variant(items):
        preds, valids, rois = [], [], []
        for s in range(0, len(items), batch_size):
            chunk = items[s:s + batch_size]
            batch = collator(chunk)
            n_tg = batch.get("n_targets")
            if n_tg is not None:
                assert int(n_tg.sum()) == len(chunk), (
                    "this function assumes single-channel / single-target rows (the MMTR forecasting corpus has no covariates); "
                    "sum of n_targets differs from the number of samples -- extra multi-target expansion logic would be needed")
            batch_dev = _to_device(batch)
            fl = batch["future"].shape[-1]
            with torch.no_grad():
                out = model.generate_forecast_teacher_forced(batch_dev, horizon=fl)
            qp = out["quantile_preds"].detach().cpu().float().numpy()[..., :fl]
            gt_np = batch["future"].numpy()
            valid = ~np.isnan(gt_np)
            roi_np = batch["roi_mask"].numpy()
            for i in range(qp.shape[0]):
                preds.append(qp[i]); valids.append(valid[i]); rois.append(roi_np[i])
        return preds, valids, rois

    band_order = BANDS  # same band order as the (b) aggregation (tiny/well_below/mod_below/typical/above)
    report = {"experiments": {}, "examples": []}
    for scale in gate_scales:
        with torch.no_grad():
            for (_, p), orig_p in zip(_gate_params(model), gate_snapshot):
                p.copy_(orig_p * scale)
        variants = ["orig"] + band_order
        band_preds = {}
        ref_valid = ref_roi = None
        examples = ([{"row": int(i), "id": str(ids[i]), "dataset_name": str(ds_names[i]), "bands": {}}
                     for i in range(min(dump_examples, n))] if scale == gate_scales[0] else [])
        for band in variants:
            sub = sub_df_base.copy()
            if band != "orig":
                if variant_mode == "advisory":
                    sub = apply_advisory_variant(sub, band)
                else:
                    sub["conclusion"] = [edit_conclusion(c, BAND_CLAUSES[band], band=band)
                                          for c in sub["conclusion"]]
            vds = _variant_dataset(base_ds, sub)
            items = _build_items_strict(vds)
            for ex in examples:  # plumbing-check material: tail of the rendered text after editing (for manual verification)
                ex["bands"][band] = tok.decode(items[ex["row"]]["input_ids"], skip_special_tokens=False)[-500:]
            preds, valids, rois = _run_variant(items)
            band_preds[band] = preds
            if band == "orig":
                ref_valid, ref_roi = valids, rois
            else:
                # Alignment guard: future/roi must not change with the conclusion edit; a mismatch means the
                # row order drifted between variants.
                for i in range(n):
                    if not (np.array_equal(valids[i], ref_valid[i]) and np.array_equal(rois[i], ref_roi[i])):
                        raise RuntimeError(f"row {i} (band={band}): valid/roi differ from orig -- row order drifted between variants")

        peak_mat = np.full((len(band_order), n), np.nan)
        mean_mat = np.full((len(band_order), n), np.nan)
        for bi, band in enumerate(band_order):
            for i in range(n):
                pk, mn = _row_peak_mean(band_preds[band][i], ref_valid[i], ref_roi[i], median_idx)
                peak_mat[bi, i] = pk; mean_mat[bi, i] = mn
        orig_pk = np.array([_row_peak_mean(band_preds["orig"][i], ref_valid[i], ref_roi[i], median_idx)[0]
                            for i in range(n)])
        orig_mn = np.array([_row_peak_mean(band_preds["orig"][i], ref_valid[i], ref_roi[i], median_idx)[1]
                            for i in range(n)])
        denom = np.where(typ_ok, typ, np.nan)
        peak_ratio, mean_ratio = peak_mat / denom, mean_mat / denom
        orig_pk_ratio, orig_mn_ratio = orig_pk / denom, orig_mn / denom
        peak_summary = _rank_summary(peak_ratio, orig_pk_ratio, typ_ok, band_order)
        mean_summary = _rank_summary(mean_ratio, orig_mn_ratio, typ_ok, band_order)
        # Per-domain split (intersected with typ_ok) -- _rank_summary still computes when a domain has very
        # few rows; downstream reports must flag such cells as "small sample, noise-dominated" (the same
        # caveat the main table applies to the small Climate subset).
        peak_by_domain, mean_by_domain = {}, {}
        for dom in sorted(set(domains.tolist())):
            dom_mask = typ_ok & (domains == dom)
            peak_by_domain[dom] = _rank_summary(peak_ratio, orig_pk_ratio, dom_mask, band_order)
            mean_by_domain[dom] = _rank_summary(mean_ratio, orig_mn_ratio, dom_mask, band_order)

        if save_per_sample_raw:
            os.makedirs(os.path.dirname(os.path.abspath(save_per_sample_raw)) or ".", exist_ok=True)
            np.savez(
                save_per_sample_raw,
                peak_ratio=peak_ratio, mean_ratio=mean_ratio,
                orig_pk_ratio=orig_pk_ratio, orig_mn_ratio=orig_mn_ratio,
                typ_ok=typ_ok, ids=ids, dataset_names=ds_names, domains=domains,
                band_order=np.array(band_order), gate_scale=np.array(scale),
            )
            saved_path = save_per_sample_raw if save_per_sample_raw.endswith(".npz") \
                else save_per_sample_raw + ".npz"
            print(f"[fresh_forward] raw per-sample, per-band matrices written -> {saved_path} "
                  f"(peak_ratio/mean_ratio shape={peak_ratio.shape}; for post-hoc band-label shuffling "
                  f"to recompute the null distribution)")

        # Plumbing self-check (ignores direction; only asks whether the edit changed the model output at all,
        # to catch "batching / edit did not take effect" script bugs -- 0 means the variant forecasts are
        # bitwise equal, i.e. a bug; non-zero with still-random direction means the path is connected and
        # the feedback is simply too weak / non-directional, a genuine mechanism finding rather than a
        # script problem).
        a_preds, b_preds = band_preds["above"], band_preds["well_below"]
        raw_diff = np.array([float(np.nanmax(np.abs(a_preds[i] - b_preds[i]))) for i in range(n)])
        plumbing = {
            "frac_rows_pred_changed_above_vs_well_below": float(np.mean(raw_diff > 1e-6)),
            "mean_abs_raw_diff_above_vs_well_below": float(np.nanmean(raw_diff)),
        }
        report["experiments"][str(scale)] = {
            "n": n, "peak": peak_summary, "roi_mean": mean_summary, "plumbing_check": plumbing,
            "peak_by_domain": peak_by_domain, "roi_mean_by_domain": mean_by_domain,
        }
        if examples:
            report["examples"] = examples
        p_sum = peak_summary
        print(f"[fresh_forward][gate={scale}] n={n} peak Spearman={p_sum['spearman_mean']:.3f} "
              f"(rho>0 {p_sum['spearman_pos_rate']:.2f}, strictly monotone {p_sum['strict_mono_rate']:.2f}) "
              f"above>well_below={p_sum['dir_follow_rate(above>well_below)']:.2f} "
              f"above>tiny={p_sum['dir_follow_rate(above>tiny)']:.2f} "
              f"mean_abs_dev_vs_orig={p_sum['mean_abs_dev_vs_orig']:.4f} | "
              f"plumbing: fraction of rows whose forecast changed={plumbing['frac_rows_pred_changed_above_vs_well_below']:.2f}"
              f" (above vs well_below raw quantile tensor, mean of max|diff|="
              f"{plumbing['mean_abs_raw_diff_above_vs_well_below']:.4f})")
        print(f"{'domain':10} {'n':>4} | {'peak spearman':>13} | {'peak dir>tiny':>13} | "
              f"{'roi_mean spearman':>18} | {'roi_mean dir>tiny':>18}")
        print("-" * 90)
        for dom in ["ALL"] + sorted(set(domains.tolist())):
            pd_, md_ = (peak_summary, mean_summary) if dom == "ALL" else (peak_by_domain[dom], mean_by_domain[dom])
            print(f"{dom:10} {pd_['n']:>4} | {pd_['spearman_mean']:>13.3f} | "
                  f"{pd_['dir_follow_rate(above>tiny)']:>13.3f} | "
                  f"{md_['spearman_mean']:>18.3f} | {md_['dir_follow_rate(above>tiny)']:>18.3f}")

    with torch.no_grad():  # restore the gates to their checkpoint values (in case the model object is reused)
        for (_, p), orig_p in zip(_gate_params(model), gate_snapshot):
            p.copy_(orig_p)

    report.update({
        "model_path": os.path.abspath(model_path), "parquet": parquet,
        "n_samples": n, "seed": seed, "band_clauses": BAND_CLAUSES,
        "variant_mode": variant_mode,
        "sampled_positions": idx.tolist(),
        "caveats": [
            "If the checkpoint was trained with the gate zero-initialised (gate_init=0, the code default), "
            "the trained gate may have stayed near zero (|tanh(gate)| of roughly 0.005 was observed, i.e. the "
            "feedback contributes about 0.5% of the residual). A negative result ('forecast does not follow "
            "the instruction direction') on such a checkpoint only shows that the feedback channel is too "
            "narrow under that gate configuration; it does not show that the LLM->Chronos-2 feedback "
            "mechanism itself is ineffective. Re-run this function with --model_path pointing at a "
            "checkpoint trained with GATE_INIT=1.0 + --zero_cross_out_proj (the released configuration) to compare.",
        ],
    })
    if output:
        os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
        with open(output, "w", encoding="utf-8") as f:
            json.dump(report, f, ensure_ascii=False, indent=2)
        print(f"[fresh_forward] written -> {output}")
    return report


# ---------------------------------------------------------------- supplementary: Qwen3.5-9B as an independent VLM judge
def vlm_judge_report(root_pair=("outputs/eval/controllability/above", "outputs/eval/controllability/well_below"),
                     parquet="outputs/eval/controllability/parquets/ctrl_orig.parquet",
                     n_samples=20, seed=0, out_dir="outputs/eval/causal_faithfulness_vlm"):
    """Supplementary cross-check (not the main line): render the forecast curves of the above/well_below
    counterfactual variants and let the local Qwen3.5-9B (a generic VLM judge independent of the
    ChronosLLM training/inference pipeline and of our cross-attention feedback architecture) blindly pick
    "which image looks more like the instructed direction", cross-validating the numeric
    direction-agreement rate (pair_dir_rate). Loaded via AutoModelForImageTextToText + AutoProcessor (the
    native multimodal Qwen3_5ForConditionalGeneration class, not the text-only AutoModelForCausalLM
    wrapper in chronos_llm/models)."""
    import io
    import torch
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from transformers import AutoModelForImageTextToText, AutoProcessor
    from PIL import Image

    os.makedirs(out_dir, exist_ok=True)
    test = pd.read_parquet(parquet).reset_index(drop=True)
    above_root, below_root = root_pair
    za = np.load(os.path.join(above_root, "forecast_preds_tf.npz"), allow_pickle=True)
    zb = np.load(os.path.join(below_root, "forecast_preds_tf.npz"), allow_pickle=True)
    assert list(za["ids"]) == list(zb["ids"]), "the above/well_below npz files must share the same row order for paired comparison"
    ids = list(za["ids"])
    id_to_row = {rid: i for i, rid in enumerate(test["id"])}

    rng = random.Random(seed)
    cand = [i for i, rid in enumerate(ids) if rid in id_to_row]
    rng.shuffle(cand)
    sample_idx = cand[:n_samples]

    print(f"[VLM judge] loading Qwen3.5-9B ({QWEN_VL_PATH}) as an independent VLM judge ...")
    model = AutoModelForImageTextToText.from_pretrained(
        QWEN_VL_PATH, trust_remote_code=True, dtype=torch.bfloat16
    ).eval().to("cuda")
    processor = AutoProcessor.from_pretrained(QWEN_VL_PATH, trust_remote_code=True)

    def _median(z, i):
        q = z["pred_quantiles"][i]
        return q[q.shape[0] // 2]

    def _render(i, rid, swap):
        """swap=False: panel A = above, panel B = well_below; swap=True reverses them (guards against
        position bias). Returns (PIL.Image, correct answer letter)."""
        row = test.iloc[id_to_row[rid]]
        hist = np.asarray(row["history_values"], dtype=float)
        if hist.ndim > 1:
            hist = hist[0]
        hist = hist[np.isfinite(hist)][-200:]
        pa, pb = _median(za, i), _median(zb, i)
        valid = zb["valid_mask"][i].astype(bool)
        pa, pb = pa[valid], pb[valid]
        fig, axes = plt.subplots(1, 2, figsize=(8, 3), sharey=True)
        panels = [("A", pa), ("B", pb)] if not swap else [("A", pb), ("B", pa)]
        correct_letter = "A" if not swap else "B"  # letter of the panel showing the 'above' forecast
        for ax, (letter, pred) in zip(axes, panels):
            hx = np.arange(len(hist))
            px = np.arange(len(hist), len(hist) + len(pred))
            ax.plot(hx, hist, color="gray", label="history")
            ax.plot(px, pred, color="tab:blue", label="forecast")
            ax.axvline(len(hist), color="black", linestyle=":", linewidth=0.8)
            ax.set_title(f"panel {letter}")
        fig.tight_layout()
        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=110)
        plt.close(fig)
        buf.seek(0)
        return Image.open(buf).convert("RGB"), correct_letter

    n_ok, n_tot, rows = 0, 0, []
    for i in sample_idx:
        rid = ids[i]
        swap = bool(rng.getrandbits(1))
        img, correct = _render(i, rid, swap)
        img_path = os.path.join(out_dir, f"{rid.replace('/', '_')}.png")
        img.save(img_path)
        prompt = (
            "You are comparing two forecast panels (A and B) for the same series. Both show the "
            "same recent history (gray) followed by two DIFFERENT candidate forecasts (blue). "
            "One candidate was generated under an instruction saying the upcoming peak will run "
            "WELL ABOVE the series' typical high level; the other under an instruction saying the "
            "peak will run WELL BELOW the series' typical high level. "
            "Judging purely from the shapes shown, which panel (A or B) more plausibly corresponds "
            "to the 'well ABOVE typical' instruction? Answer with exactly one letter: A or B."
        )
        messages = [{"role": "user", "content": [
            {"type": "image", "image": img_path}, {"type": "text", "text": prompt},
        ]}]
        inputs = processor.apply_chat_template(
            messages, tokenize=True, add_generation_prompt=True,
            return_dict=True, return_tensors="pt"
        ).to(model.device)
        with torch.no_grad():
            gen = model.generate(**inputs, max_new_tokens=8, do_sample=False)
        text = processor.decode(gen[0, inputs["input_ids"].shape[1]:], skip_special_tokens=True)
        m = re.search(r"\b(A|B)\b", text.strip().upper())
        answer = m.group(1) if m else None
        is_ok = answer == correct
        n_tot += 1
        n_ok += int(is_ok)
        rows.append(dict(id=rid, correct=correct, answer=answer, raw=text.strip(), ok=is_ok))
        print(f"  {rid}: correct={correct} Qwen answer={answer!r} {'OK' if is_ok else 'MISS'}  (raw output={text.strip()!r})")

    rate = n_ok / n_tot if n_tot else float("nan")
    print(f"\n[VLM judge] n={n_tot} direction-agreement rate={rate:.3f} (random baseline 0.5)")
    pd.DataFrame(rows).to_csv(os.path.join(out_dir, "vlm_judge_results.csv"), index=False)
    print(f"  details saved -> {os.path.join(out_dir, 'vlm_judge_results.csv')}; images in the same directory")
    return dict(n=n_tot, agree_rate=rate)


