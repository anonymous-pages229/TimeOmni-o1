# ---------------------------------------------------------------- (a) gate=0 identity
def gate_identity_report():
    """Re-verify that with gate=0 Chronos2WithCrossAttn is numerically identical to the original
    Chronos2Model (same loading logic as test_cross_attn_identity, so the report is self-contained and
    does not require that test file to have been run)."""
    import torch
    import safetensors.torch as st
    from chronos.chronos2 import Chronos2Model
    from chronos.chronos2.config import Chronos2CoreConfig
    from chronos_llm.models.cross_attn_chronos import load_chronos2_with_cross_attn

    torch.manual_seed(0)
    cfg = Chronos2CoreConfig.from_pretrained(CHRONOS_CKPT)
    base = Chronos2Model(cfg)
    base.load_state_dict(st.load_file(CHRONOS_CKPT + "/model.safetensors"), strict=False)
    base = base.eval()
    xattn = load_chronos2_with_cross_attn(CHRONOS_CKPT)

    B, L, n_out, M = 2, 160, 4, 16
    context = torch.randn(B, L)
    cross = torch.randn(B, M, xattn.config.d_model)
    cross_mask = torch.ones(B, M)
    with torch.no_grad():
        out_base = base(context=context, num_output_patches=n_out)
        out_gate0 = xattn(context=context, num_output_patches=n_out,
                          cross_states=cross, cross_states_mask=cross_mask)
    diff = (out_base.quantile_preds - out_gate0.quantile_preds).abs().max().item()
    ok = diff < 1e-4
    print(f"[identity ablation] gate=0: max|base - xattn(cross_states provided)| = {diff:.3e} "
          f"{'OK: exactly identical' if ok else 'FAIL: not identical -- mechanism-level problem!'}")
    print("  => without textual feedback the model is numerically the original Chronos-2 "
          "(a mechanism guarantee, not a training outcome).")
    return ok


# ---------------------------------------------------------------- (b) counterfactual: aggregate existing outputs
def _peak(v):
    v = list(v) if not isinstance(v, (list, np.ndarray)) else v
    if len(v) and np.ndim(v[0]) > 0:
        v = v[0]
    a = np.asarray(v, dtype=float)
    a = a[np.isfinite(a)]
    return float(np.nanmax(a)) if a.size else np.nan


def _pred_peaks(npz_path):
    z = np.load(npz_path, allow_pickle=True)
    q = z["pred_quantiles"]
    med = q[:, q.shape[1] // 2, :]
    valid = z["valid_mask"].astype(bool)
    roi = valid & (z["roi_mask"] > 0.5)
    peaks = np.full(len(med), np.nan)
    for i in range(len(med)):
        m = roi[i] if roi[i].any() else valid[i]
        if m.any():
            peaks[i] = np.nanmax(med[i][m])
    return peaks


def counterfactual_report(root, parquet, label):
    """Aggregate the teacher-forced forecasts of the 5 bands + orig under ``root`` into causal-faithfulness
    numbers. Equivalent to the core computation of eval_controllability_metrics.py, reworded here in
    "causal faithfulness" terms."""
    test = pd.read_parquet(parquet)
    ds_names = test["dataset_name"].astype(str).to_numpy()
    pk = test["future_values"].map(_peak)
    typ_map = pk.groupby(test["dataset_name"]).quantile(0.90).to_dict()
    typ = np.array([typ_map.get(d, np.nan) for d in ds_names])
    typ_ok = np.isfinite(typ) & (typ > 1e-9)

    orig = _pred_peaks(os.path.join(root, "orig", "forecast_preds_tf.npz")) / np.where(typ_ok, typ, np.nan)
    mat = np.stack([
        _pred_peaks(os.path.join(root, b, "forecast_preds_tf.npz")) / np.where(typ_ok, typ, np.nan)
        for b in BANDS
    ])

    idx = np.where(typ_ok)[0]
    rhos = []
    for i in idx:
        col = mat[:, i]
        if np.isfinite(col).all():
            r = spearmanr(np.arange(len(BANDS)), col).statistic
            if np.isfinite(r):
                rhos.append(r)
    rhos = np.array(rhos)
    ab, wb = mat[BANDS.index("above"), idx], mat[BANDS.index("well_below"), idx]
    ok = np.isfinite(ab) & np.isfinite(wb)
    # This line is the "one-off counterfactual check" itself: above vs well_below is the most extreme pair
    # of counterfactual instructions, checked on all 444 test rows (not a single sampled row).
    pair_dir_rate = float(np.mean(ab[ok] > wb[ok])) if ok.any() else float("nan")
    spearman_mean = float(np.mean(rhos)) if rhos.size else float("nan")
    perturb = float(np.nanmean(np.abs(mat[BANDS.index("above"), idx] - orig[idx])))

    if spearman_mean > 0.3 and pair_dir_rate > 0.7:
        verdict = "FAITHFUL (forecast clearly follows the instruction direction)"
    elif spearman_mean > 0.1 or pair_dir_rate > 0.55:
        verdict = "WEAKLY FAITHFUL (weak directional signal, too small to call 'faithful')"
    else:
        verdict = "NOT FAITHFUL (forecast essentially ignores the instruction, near random)"

    print(f"\n[counterfactual test] {label}")
    print(f"  n={len(idx)} (rows of the 444-row test set with an estimable typical peak)")
    print(f"  single-pair counterfactual (above vs well_below) direction-agreement rate = {pair_dir_rate:.3f}"
          f" (random baseline 0.5; this is the one-off check, here over all rows rather than one sample)")
    print(f"  5-band magnitude Spearman monotonicity mean = {spearman_mean:.3f}"
          f" (supplementary: instructions are not just binary -- is the response ordered overall?)")
    print(f"  forecast perturbation of 'above' relative to orig = {perturb:.4f}"
          f" (response magnitude: even if the direction is right, is the shift negligibly small?)")
    print(f"  => verdict: {verdict}")
    return dict(label=label, n=len(idx), pair_dir_rate=pair_dir_rate,
                spearman_mean=spearman_mean, perturb=perturb, verdict=verdict)


